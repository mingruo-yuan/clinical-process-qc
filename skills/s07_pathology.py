class PathologyInterpreter(AgentSkill):
    def __init__(self):
        super().__init__()

    def _define_config(self) -> SkillConfig:
        return SKILL_CONFIG

    def _execute_steps(self, patient_data: Dict, context: str) -> Dict:
        user_prompt = f"""请解读以下患者的术后病理报告:

{context}

请按照执行步骤进行解读，并以JSON格式返回结果。"""

        return call_llm_json(SYSTEM_PROMPT, user_prompt, on_chunk=getattr(self, "_kwargs", {}).get("on_chunk"))

    def _apply_constraints(self, raw_result: Dict, patient_data: Dict) -> Dict:
        return raw_result

    def _format_output(self, result: Dict) -> Dict:
        path = result.get("病理小结", {})
        return {
            "总结": result.get("总结", f"病理解读: {path.get('诊断', '')}"),
            "置信度": result.get("置信度", 0.95),
            "病理小结": path,
            "免疫组化解读": result.get("免疫组化解读", []),
            "治疗建议": result.get("治疗建议", {}),
            "药物推荐": result.get("药物推荐", {}),
            "标注": result.get("标注", []),
            "警告": result.get("警告", []),
            "建议": result.get("建议", []),
            "参考": result.get("参考", []),
        }
